"""Import reviewed Aseprite exports without changing pixels or old source assets."""
import argparse
import json
from pathlib import Path
import shutil
from PIL import Image

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
source = args.source.resolve()
root = Path(__file__).resolve().parents[1]
output = root / 'art/fazendeiro_animado'
docs = root / 'docs/arte_fazendeiro'
output.mkdir(parents=True, exist_ok=True)
(docs / 'fontes').mkdir(parents=True, exist_ok=True)
(docs / 'previas').mkdir(parents=True, exist_ok=True)
(docs / '.gdignore').write_text('', encoding='utf-8')
cycles = json.loads((source / 'cycles.json').read_text(encoding='utf-8'))
actor = {}
for name, data in cycles.items():
    frames = []
    for index in range(len(data['durations'])):
        png = source / name / f'{name}_{index}.png'
        with Image.open(png) as im:
            assert im.size == (128, 128), png
            assert im.mode == 'RGBA', (png, im.mode)
        target = output / f'fazendeiro_{name}_{index:02}.png'
        shutil.copy2(png, target)
        frames.append(f'res://art/fazendeiro_animado/{target.name}')
    actor[name] = {'frames': frames, 'fps': 1000 / (sum(data['durations']) / len(frames)),
                   'durations_ms': data['durations'], 'loop': data['loop'], 'offset': [0, -16]}
    shutil.copy2(source / name / f'fazendeiro_{name}.aseprite', docs / 'fontes')
    for filename in [f'{name}.gif', f'{name}_filmstrip.png', f'{name}_sheet.png', f'{name}_sheet.json', 'validation.json']:
        target = docs / 'previas' / name
        target.mkdir(exist_ok=True)
        shutil.copy2(source / name / filename, target / filename)
for filename in ['CONCEITO.md', 'cycles.json']:
    shutil.copy2(source / filename, docs / filename)
for filename in ['farmer-design.mjs', 'build-farmer.mjs', 'artist-client.mjs']:
    shutil.copy2(source.parent / 'aseprite-ai-artist' / filename, docs / 'fontes' / filename)
(output / 'catalog.json').write_text(json.dumps(actor, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(root / 'farmer_art_data.gd').write_text('extends RefCounted\n\n# Generated by tools/install_farmer_animation.py from reviewed Aseprite exports.\nconst DATA: Dictionary = ' + json.dumps(actor, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'Imported {sum(len(c["frames"]) for c in actor.values())} frames, {len(actor)} cycles and editable sources.')
