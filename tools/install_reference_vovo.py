"""Validate and copy reviewed Vovó exports; no raster edits."""
from pathlib import Path
import argparse, json, shutil
from PIL import Image

parser=argparse.ArgumentParser()
parser.add_argument('--source',type=Path,required=True)
args=parser.parse_args()
source=args.source.resolve()
root=Path(__file__).resolve().parents[1]
output=root/'art/vovo_resistente'
docs=root/'docs/arte_vovo_resistente'
output.mkdir(parents=True,exist_ok=True)
(docs/'fontes').mkdir(parents=True,exist_ok=True)
(docs/'.gdignore').write_text('',encoding='utf-8')
cycles=json.loads((source/'cycles.json').read_text(encoding='utf-8'))
actor={}
for state in ['idle','walk','run','idle_plant','death']:
    data=cycles[state]
    paths=[]
    for index in range(len(data['durations'])):
        original=source/state/f'{state}_{index}.png'
        with Image.open(original) as image:
            assert image.mode=='RGBA' and image.size==(128,128),original
            alpha=image.getchannel('A')
            assert set(alpha.tobytes())=={0,255},original
            b=alpha.getbbox()
            assert b and b[0]>=2 and b[1]>=2 and b[2]<=126 and b[3]<=126,(original,b)
            assert not any(r>180 and b>180 and g<80 and a for r,g,b,a in zip(*[iter(image.tobytes())]*4)),original
        filename=f'vovo_{state}_{index:02}.png'
        shutil.copy2(original,output/filename)
        paths.append(f'res://art/vovo_resistente/{filename}')
    actor[state]={'frames':paths,'fps':1000*len(paths)/sum(data['durations']),
                  'durations_ms':data['durations'],'loop':data['loop'],'offset':[0,-16]}
    shutil.copy2(source/state/f'vovo_{state}.aseprite',docs/'fontes')
    previews=docs/'previas'/state
    previews.mkdir(parents=True,exist_ok=True)
    for filename in [f'{state}.gif',f'{state}_filmstrip.png',f'{state}_sheet.png',f'{state}_sheet.json','validation.json']:
        shutil.copy2(source/state/filename,previews/filename)
for filename in ['prepare-reference-vovo.lua','fix-vovo-gait.lua','assemble-reference-vovo.lua','export-reference-vovo.mjs','artist-client.mjs','plan-vovo.py']:
    shutil.copy2(source.parent/'aseprite-ai-artist'/filename,docs/'fontes')
(output/'catalog.json').write_text(json.dumps(actor,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(root/'vovo_art_data.gd').write_text('extends RefCounted\n\n# Generated by tools/install_reference_vovo.py from reviewed exports.\nconst DATA: Dictionary = '+json.dumps(actor,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Integrated {sum(len(a["frames"]) for a in actor.values())} Vovó frames, {len(actor)} cycles; RGBA, margins and magenta check passed.')
