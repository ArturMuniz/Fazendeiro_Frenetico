"""Copy reviewed reference-faithful Aseprite exports into the game; no raster edits."""
from pathlib import Path
import argparse
import json
import shutil
from PIL import Image

parser=argparse.ArgumentParser()
parser.add_argument('--source',type=Path,required=True)
args=parser.parse_args()
source=args.source.resolve()
root=Path(__file__).resolve().parents[1]
output=root/'art/fazendeiro_fiel'
docs=root/'docs/arte_fazendeiro_fiel'
output.mkdir(parents=True,exist_ok=True)
(docs/'fontes').mkdir(parents=True,exist_ok=True)
(docs/'.gdignore').write_text('',encoding='utf-8')
cycles=json.loads((source/'cycles.json').read_text(encoding='utf-8'))
actor={}
for name in ['idle','walk','run','idle_hat','idle_swat','death']:
    data=cycles[name]
    paths=[]
    for index in range(len(data['durations'])):
        original=source/name/f'{name}_{index}.png'
        with Image.open(original) as image:
            assert image.mode=='RGBA' and image.size==(128,128),original
        filename=f'fazendeiro_{name}_{index:02}.png'
        shutil.copy2(original,output/filename)
        paths.append(f'res://art/fazendeiro_fiel/{filename}')
    actor[name]={'frames':paths,'fps':1000*len(paths)/sum(data['durations']),
                 'durations_ms':data['durations'],'loop':data['loop'],'offset':[0,-16]}
    shutil.copy2(source/name/f'fazendeiro_{name}.aseprite',docs/'fontes')
    previews=docs/'previas'/name
    previews.mkdir(parents=True,exist_ok=True)
    for filename in [f'{name}.gif',f'{name}_filmstrip.png',f'{name}_sheet.png',f'{name}_sheet.json','validation.json']:
        shutil.copy2(source/name/filename,previews/filename)
for filename in ['prepare-reference-farmer.lua','finish-reference-farmer.lua','export-reference-farmer.mjs','artist-client.mjs']:
    shutil.copy2(source.parent/'aseprite-ai-artist'/filename,docs/'fontes')
(output/'catalog.json').write_text(json.dumps(actor,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(root/'farmer_art_data.gd').write_text('extends RefCounted\n\n# Generated by tools/install_reference_farmer.py from reviewed reference-faithful exports.\nconst DATA: Dictionary = '+json.dumps(actor,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Integrated {sum(len(a["frames"]) for a in actor.values())} frames, {len(actor)} cycles.')
